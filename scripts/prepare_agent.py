"""Package the shared platform source into the standalone app deployment directories.

Edit databricks/platform, not the generated copies. Run before every Agent Bricks deployment.
"""
from pathlib import Path
import argparse
import shutil

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'databricks/platform'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--target', choices=['magneto-director', 'magneto-companion'], help='Package only one app')
args = parser.parse_args()
targets = [ROOT / 'databricks' / name for name in
           ([args.target] if args.target else ['magneto-director', 'magneto-companion'])]

for target in targets:
    shutil.copytree(source / 'magneto_platform', target / 'magneto_platform', dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns('__pycache__', '*.pyc'))
    shutil.copyfile(source / 'services.toml', target / 'services.toml')
    (target / 'magneto_platform/GENERATED.txt').write_text(
        'Generated by scripts/prepare_agent.py from databricks/platform. Do not edit this deployment copy.\n')
    print(f'Packaged shared service adapters and services.toml for {target.name}.')

if any(target.name == 'magneto-director' for target in targets):
    # Bundle the authoritative v1 research contracts and resource references for the director.
    director = ROOT / 'databricks/magneto-director'
    contracts = director / 'agent/research_contracts'
    contracts.mkdir(exist_ok=True)
    for name in ('retrieval-request', 'retrieval-result'):
        shutil.copyfile(ROOT / f'databricks/contracts/v1/{name}.schema.json',
                        contracts / f'{name}.schema.json')
    shutil.copyfile(ROOT / 'databricks/research-pipeline/config/operations.toml', director / 'research.toml')
    (contracts / 'GENERATED.txt').write_text('Generated by scripts/prepare_agent.py from databricks/contracts/v1. Do not edit.\n')

if any(target.name == 'magneto-director' for target in targets):
    catalog = ROOT / 'databricks/contracts/v3/activity-catalog.json'
    shutil.copyfile(catalog, director / 'learning/activity-catalog.json')
    (ROOT / 'web/learn/activity-catalog.js').write_text(
        '// Generated from databricks/contracts/v3/activity-catalog.json by scripts/prepare_agent.py.\n'
        + 'export const ACTIVITY_CATALOG = ' + catalog.read_text().strip() + ';\n')
